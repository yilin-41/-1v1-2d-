#pragma once
#include <QString>
#include <QColor>
#include <cmath>

// ============================================================================
// 常量定义
// ============================================================================
const double PI = 3.14159265358979323846;  // 圆周率常量，用于角度计算与弧度转换

// ============================================================================
// 游戏状态机枚举
// 控制整个游戏流程的状态切换（标题→购买→战斗→结算→比赛结束）
// ============================================================================
enum GameState {
    LOADING_SCREEN,   // 加载屏幕（显示游戏标题、加载进度条）
    START_SCREEN,     // 开始界面（双人就绪等待）
    BUY_PHASE,        // 购买阶段（选择武器与道具）
    PLAYING,          // 战斗阶段（实时对战）
    PAUSED,           // 暂停状态
    ROUND_OVER,       // 回合结束（展示战报、等待下一局）
    MATCH_OVER        // 整场比赛结束（抢8胜制）
};

// ============================================================================
// 投掷物类型枚举
// ============================================================================
enum GrenadeType {
    G_HE,      // 高爆手雷：大范围高伤害
    G_MOLOTOV, // 燃烧瓶：在地面生成持续伤害火焰区域
    G_SMOKE    // 烟雾弹：生成遮蔽视线的烟雾区域
};

// ============================================================================
// 武器数据结构
// 定义游戏中每一把武器的所有属性
// ============================================================================
struct Weapon {
    QString name;       // 武器名称（显示用）
    double damage;      // 单发基础伤害值
    double recoil;      // 后坐力（对玩家移动速度的反向推进力）
    double bulletSpeed; // 子弹飞行速度（像素/帧）
    int fireCooldown;   // 开火冷却时间（帧数），控制射速
    int maxAmmo;        // 单个弹匣最大弹药量
    int currentAmmo;    // 当前弹匣内剩余弹药
    int magsLeft;       // 备用弹匣数量
    bool isMelee;       // 是否为近战武器（true=匕首等近战）
    int reloadTime;     // 换弹所需时间（帧数）
    double spread;      // 子弹散布角度（度），值越大越不精准
    int price;          // 购买价格（$）
    int killReward;     // 击杀奖励（$），爆头额外+200
    bool unlocked;      // 是否已解锁/购买
    int pellets;        // 每次开火射出的弹丸数量（霰弹枪=6，其他=1）
};

// ============================================================================
// 子弹数据结构
// 在游戏世界中飞行的子弹实体
// ============================================================================
struct Bullet {
    double x, y;        // 子弹当前坐标（像素）
    double vx, vy;      // 子弹速度分量（像素/帧）
    double damage;      // 该子弹的伤害值（已计入武器基础伤害）
    QString weaponName; // 发射该子弹的武器名（用于击杀统计）
    bool isHeadshot;    // 是否命中头部（预留标记，实际由碰撞检测判定）
    bool isSniper;      // 是否为狙击枪子弹（影响弹道拖尾效果长度）
};

// ============================================================================
// 飞行中的战术投掷物
// 玩家投出后在空中飞行阶段的 grenade 实体
// ============================================================================
struct FlyingGrenade {
    double x, y;        // 当前位置
    double vx, vy;      // 速度分量
    int fuseTimer;      // 引信倒计时（帧数），归零时爆炸/生效
    GrenadeType type;   // 投掷物类型（HE/燃烧/烟雾）
    int owner;          // 投掷者标识：1=P1(CT), 2=P2(T)
};

// ============================================================================
// 火焰区域（燃烧瓶引爆后产生的地面持续伤害区）
// ============================================================================
struct FireZone {
    double x, y;        // 火焰区域中心坐标
    int duration;       // 剩余持续时间（帧数），归零后消失
    int owner;          // 火焰归属者（用于击杀判定）
};

// ============================================================================
// 烟雾区域（烟雾弹生效后的遮蔽区）
// ============================================================================
struct SmokeZone {
    double x, y;        // 烟雾区域中心坐标
    int duration;       // 剩余持续时间（帧数），归零后消散
};

// ============================================================================
// 视觉特效：掉落弹匣
// 换弹时从武器中弹出的弹匣，具有物理运动（速度、旋转）
// ============================================================================
struct DroppedMag {
    double x, y;        // 位置
    double vx, vy;      // 速度（会逐渐衰减模拟摩擦力）
    double angle;       // 当前旋转角度（度）
    double vAngle;      // 旋转角速度（度/帧，逐渐衰减）
    int life;           // 剩余生命（帧数），归零后移除
};

// ============================================================================
// 视觉特效：弹道拖尾
// 子弹飞行时的可见轨迹线，狙击枪拖尾更长更明显
// ============================================================================
struct Tracer {
    double startX, startY;  // 拖尾起点（枪口位置）
    double endX, endY;      // 拖尾终点（随子弹移动延伸）
    int life;               // 剩余生命（帧数）
    int maxLife;            // 最大生命（用于亮度衰减计算）
    bool isSniper;          // 是否为狙击枪拖尾（影响颜色与长度）
};

// ============================================================================
// 视觉特效：枪口闪光
// 开火瞬间在枪口位置产生的短暂闪光
// ============================================================================
struct MuzzleFlash {
    double x, y;        // 闪光位置
    double angle;       // 闪光朝向（对应玩家面向方向）
    int life;           // 剩余生命（帧数），通常很短
};

// ============================================================================
// 通用粒子特效
// 用于爆炸碎片、血液飞溅、烟雾颗粒、火焰粒子等多种场景
// ============================================================================
struct Particle {
    double x, y;        // 粒子位置
    double vx, vy;      // 粒子速度
    int life;           // 剩余生命（帧数）
    int maxLife;        // 最大生命（用于透明度与大小衰减）
    QColor color;       // 粒子颜色（RGBA）
    double size;        // 粒子大小（像素）
};

// ============================================================================
// 玩家回合统计数据
// 用于每回合结束后的战报展示，每回合重置
// ============================================================================
struct PlayerStats {
    double bodyDmgDealt = 0;        // 本回合造成的躯干/四肢伤害总量
    double headDmgDealt = 0;        // 本回合造成的爆头伤害总量（含爆头加成）
    QString lastKillWeapon = "无";   // 本回合最后一次击杀使用的武器名称
    int moneyEarnedThisRound = 0;   // 本回合获得的总金钱（含击杀奖励+回合奖励）

    // 重置统计数据（每回合开始时调用）
    void reset() {
        bodyDmgDealt = 0;
        headDmgDealt = 0;
        lastKillWeapon = "无";
        moneyEarnedThisRound = 0;
    }
};